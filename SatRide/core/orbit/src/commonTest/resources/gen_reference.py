"""Generate independent reference fixtures for SatRide core:orbit tests.

Reference implementations used (deliberately NOT the one we are writing):
  - Skyfield 1.54 (+ python-sgp4) for the TEME -> ITRF -> topocentric chain and pass events
  - pygeomag for WMM-2025 magnetic declination

SGP4 propagation itself is validated separately against the AIAA verification vectors;
what these fixtures independently validate is our coordinate chain, pass search and Doppler.
"""

import json
import numpy as np
from skyfield.api import EarthSatellite, load, wgs84
from pygeomag import GeoMag

ts = load.timescale()

ISS_NAME = "ISS (ZARYA)"
ISS_L1 = "1 25544U 98067A   26213.47431246  .00008515  00000-0  16079-3 0  9990"
ISS_L2 = "2 25544  51.6315  75.9770 0007211   0.6648 359.4349 15.49301455578771"

sat = EarthSatellite(ISS_L1, ISS_L2, ISS_NAME, ts)

SITES = [
    {"name": "Pune", "lat": 18.5204, "lon": 73.8567, "alt_m": 560.0},
    {"name": "Wellington", "lat": -41.2865, "lon": 174.7762, "alt_m": 0.0},
]


def topocentric_samples(site, start, minutes, step_s):
    obs = wgs84.latlon(site["lat"], site["lon"], elevation_m=site["alt_m"])
    diff = sat - obs
    out = []
    n = int(minutes * 60 / step_s) + 1
    for i in range(n):
        t = ts.tt_jd(start.tt + (i * step_s) / 86400.0)
        topo = diff.at(t)
        alt, az, dist = topo.altaz()
        r = topo.position.km
        v = topo.velocity.km_per_s
        rng = float(np.linalg.norm(r))
        rate = float(np.dot(r, v) / rng)
        out.append(
            {
                "utc": t.utc_iso(places=3),
                "azDeg": round(float(az.degrees), 6),
                "elDeg": round(float(alt.degrees), 6),
                "rangeKm": round(rng, 6),
                "rangeRateKmS": round(rate, 9),
            }
        )
    return out


def subpoint_samples(start, minutes, step_s):
    out = []
    n = int(minutes * 60 / step_s) + 1
    for i in range(n):
        t = ts.tt_jd(start.tt + (i * step_s) / 86400.0)
        geo = sat.at(t)
        sp = wgs84.subpoint(geo)
        teme_p, teme_v = geo.frame_xyz_and_velocity(
            __import__("skyfield.framelib", fromlist=["true_equator_and_equinox_of_date"]).true_equator_and_equinox_of_date
        )
        out.append(
            {
                "utc": t.utc_iso(places=3),
                "temePosKm": [round(float(x), 6) for x in teme_p.km],
                "temeVelKmS": [round(float(x), 9) for x in teme_v.km_per_s],
                "subLatDeg": round(float(sp.latitude.degrees), 6),
                "subLonDeg": round(float(sp.longitude.degrees), 6),
                "subAltKm": round(float(sp.elevation.km), 6),
                "sunlit": bool(geo.is_sunlit(load("de421.bsp"))),
                "gmstHours": round(float(t.gmst), 9),
            }
        )
    return out


def passes(site, t0, t1, min_el=0.0):
    obs = wgs84.latlon(site["lat"], site["lon"], elevation_m=site["alt_m"])
    times, events = sat.find_events(obs, t0, t1, altitude_degrees=min_el)
    diff = sat - obs
    out, cur = [], {}
    for t, e in zip(times, events):
        alt, az, _ = diff.at(t).altaz()
        rec = {"utc": t.utc_iso(places=3), "azDeg": round(float(az.degrees), 4),
               "elDeg": round(float(alt.degrees), 4)}
        if e == 0:
            cur = {"aos": rec}
        elif e == 1 and cur:
            cur["tca"] = rec
        elif e == 2 and cur.get("tca"):
            cur["los"] = rec
            out.append(cur)
            cur = {}
    return out


start = ts.utc(2026, 8, 2, 0, 0, 0)
end = ts.utc(2026, 8, 3, 0, 0, 0)

fixture = {
    "_provenance": "Generated by gen_reference.py using Skyfield 1.54 and pygeomag. "
                   "See FIXTURES.md.",
    "tle": {"name": ISS_NAME, "line1": ISS_L1, "line2": ISS_L2},
    "sites": SITES,
    "ephemeris": subpoint_samples(start, minutes=100, step_s=300),
    "topocentric": {
        s["name"]: topocentric_samples(s, start, minutes=180, step_s=60) for s in SITES
    },
    "passes": {s["name"]: passes(s, start, end) for s in SITES},
}

# WMM-2025 declination reference, spread across latitudes and both hemispheres.
gm = GeoMag()
wmm_sites = [
    ("Pune", 18.5204, 73.8567, 0.56),
    ("London", 51.5074, -0.1278, 0.0),
    ("Wellington", -41.2865, 174.7762, 0.0),
    ("Anchorage", 61.2181, -149.9003, 0.0),
    ("Quito", -0.1807, -78.4678, 2.85),
    ("Cape Town", -33.9249, 18.4241, 0.0),
]
fixture["wmm"] = {
    "epochDecimalYear": 2026.5,
    "sites": [
        {
            "name": n,
            "latDeg": la,
            "lonDeg": lo,
            "altKm": alt,
            "declinationDeg": round(
                gm.calculate(glat=la, glon=lo, alt=alt, time=2026.5).d, 6
            ),
        }
        for (n, la, lo, alt) in wmm_sites
    ],
}

with open("orbit_reference.json", "w") as f:
    json.dump(fixture, f, indent=1)

print("ephemeris samples:", len(fixture["ephemeris"]))
for s in SITES:
    print(f"{s['name']}: topo={len(fixture['topocentric'][s['name']])} "
          f"passes={len(fixture['passes'][s['name']])}")
print("wmm sites:", len(fixture["wmm"]["sites"]))
print("bytes:", len(json.dumps(fixture)))
