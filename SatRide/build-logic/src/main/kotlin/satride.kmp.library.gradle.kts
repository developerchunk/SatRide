import org.jetbrains.kotlin.gradle.dsl.JvmTarget

/**
 * Base convention for every shared SatRide module.
 *
 * Targets: Android, iosArm64, iosSimulatorArm64, JVM. The JVM target exists so pure-Kotlin
 * modules (`core:orbit`, `core:dsp`) get fast unit-test runs and so the desktop app stays
 * buildable; it is not a shipping platform commitment.
 */

plugins {
    id("org.jetbrains.kotlin.multiplatform")
    id("com.android.kotlin.multiplatform.library")
}

val jvmTargetVersion = JvmTarget.fromTarget(providers.gradleProperty("satride.jvmTarget").get())
val namespaceRoot = providers.gradleProperty("satride.namespace").get()

kotlin {
    jvm {
        compilerOptions {
            jvmTarget.set(jvmTargetVersion)
        }
    }

    iosArm64()
    iosSimulatorArm64()

    android {
        // ":core:orbit" -> "com.developerstring.satride.core.orbit"
        namespace = namespaceRoot + path.replace(":", ".").replace("-", "")
        compileSdk = providers.gradleProperty("satride.android.compileSdk").get().toInt()
        minSdk = providers.gradleProperty("satride.android.minSdk").get().toInt()

        compilerOptions {
            jvmTarget.set(jvmTargetVersion)
        }
    }

    sourceSets {
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}

/**
 * Makes `src/commonTest/resources` readable from common test code.
 *
 * commonTest has no portable resource loader, so the directory's absolute path is generated into
 * a constant and read with okio, which has a real filesystem on every target. Registered for any
 * module that has the directory, so a module gets fixtures by creating the folder.
 */
val fixtureDir = layout.projectDirectory.dir("src/commonTest/resources")
if (fixtureDir.asFile.isDirectory) {
    val generateFixtureAccessor by tasks.registering {
        val outputDir = layout.buildDirectory.dir("generated/fixtures/kotlin")
        val fixturePath = fixtureDir.asFile.absolutePath
        inputs.property("fixturePath", fixturePath)
        outputs.dir(outputDir)
        doLast {
            val file = outputDir.get().asFile
                .resolve("com/developerstring/satride/testfixtures/Fixtures.kt")
            file.parentFile.mkdirs()
            file.writeText(
                """
                |// Generated by the generateFixtureAccessor Gradle task. Do not edit.
                |package com.developerstring.satride.testfixtures
                |
                |internal const val FIXTURE_DIR: String = "$fixturePath"
                |
                """.trimMargin(),
            )
        }
    }
    kotlin.sourceSets.commonTest.configure {
        kotlin.srcDir(generateFixtureAccessor)
    }
}
