package com.developerstring.satride.feature.auth

import android.content.Context
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.platform.LocalContext
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import co.touchlab.kermit.Logger
import com.developerstring.satride.core.auth.AuthFailure
import com.developerstring.satride.core.auth.GoogleTokens
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

/**
 * Google sign-in through Credential Manager.
 *
 * Credential Manager rather than the retired `GoogleSignInClient`: it is the supported path from
 * Android 14 onward, and it is what exposes the two switches this app specifically needs.
 */
@Composable
actual fun rememberGoogleSignIn(): GoogleSignInLauncher {
    val context = LocalContext.current
    return remember(context) { CredentialManagerSignIn(context) }
}

private class CredentialManagerSignIn(private val context: Context) : GoogleSignInLauncher {

    private val logger = Logger.withTag("GoogleSignIn")

    /**
     * False when the build has no web client id.
     *
     * The sign-in screen disables its button and explains itself when this is false, which is the
     * difference between a control that is visibly unavailable and one that looks fine and then
     * fails. It was previously hardcoded `true`, so a misconfigured build offered the button and
     * only revealed the problem when somebody pressed it.
     */
    override val isAvailable: Boolean = context.webClientId() != null

    override suspend fun requestTokens(): Result<GoogleTokens> {
        // `GetSignInWithGoogleOption`, not `GetGoogleIdOption`.
        //
        // The two look interchangeable and are not. `GetGoogleIdOption` is the *silent* one-tap
        // retrieval: it returns a credential the user has already authorised for this app, and when
        // there is none it fails with `NoCredentialException` — which is exactly what happened on a
        // Pixel 6a with several Google accounts signed in, because none of them had ever used
        // SatRide. Even `setFilterByAuthorizedAccounts(false)` does not reliably rescue it; Google
        // also rate-limits that sheet once a user has dismissed it a few times.
        //
        // `GetSignInWithGoogleOption` is the explicit button flow. It always presents the full
        // account chooser, every Google account on the device is listed, and nothing is ever picked
        // automatically — which is precisely the behaviour this screen is specified to have.
        // Resolved inside the `runCatching` below, not before it.
        //
        // This used to `check()` on the way in, which threw straight past the error handling and
        // took the app down the moment somebody pressed the button. That is exactly what happened
        // in internal testing: resource shrinking had removed `default_web_client_id` from the
        // release build (see `res/raw/keep.xml`), and a missing *configuration value* became a
        // fatal crash on the most prominent control in the app. A build that cannot sign in should
        // say it cannot sign in.
        val clientId = context.webClientId()
            ?: return Result.failure(
                GoogleSignInException(
                    AuthFailure.Unexpected(
                        IllegalStateException(
                            "default_web_client_id is missing from this build — Google sign-in is " +
                                "unavailable. Generated by the google-services plugin; check it " +
                                "survived resource shrinking.",
                        ),
                    ),
                ),
            )

        val option = GetSignInWithGoogleOption.Builder(clientId).build()

        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()

        return runCatching {
            // `context` must be an Activity for the chooser to be shown. In Compose, LocalContext
            // inside an activity-hosted composition is that activity.
            val response = CredentialManager.create(context).getCredential(context, request)
            // No access token here, and none needed: Credential Manager does not issue one, and
            // Firebase's Android SDK takes a nullable one. See [GoogleTokens].
            GoogleTokens(idToken = GoogleIdTokenCredential.createFrom(response.credential.data).idToken)
        }.recoverCatching { error ->
            throw GoogleSignInException(error.toAuthFailure().also { logger.w(error) { "sign-in: $it" } })
        }
    }
}

/**
 * The OAuth **web** client id, read from the resource the google-services plugin generates.
 *
 * Looked up by name rather than through `R`, because that resource is generated into the
 * application module and a feature module cannot import the app's `R` class. The alternative —
 * copying the id into a Kotlin constant — would mean `google-services.json` was no longer the
 * single source of truth, and the two would drift the first time the Firebase project changed.
 *
 * The same trick `core:notifications` uses for its status-bar icon.
 */
private fun Context.webClientId(): String? {
    @Suppress("DiscouragedApi")
    val id = resources.getIdentifier("default_web_client_id", "string", packageName)
    return if (id == 0) null else getString(id)
}

/**
 * Maps Credential Manager's exceptions onto the app's vocabulary.
 *
 * The distinction that matters is cancellation: dismissing the sheet is a decision, not a fault,
 * and showing an error message for it would tell the user they did something wrong.
 */
private fun Throwable.toAuthFailure(): AuthFailure = when (this) {
    is GetCredentialCancellationException -> AuthFailure.Cancelled

    // Thrown when there is no account on the device, and also when every account was filtered out —
    // which cannot happen here, since filtering is switched off above.
    // With the explicit button flow this means what it says: there is no Google account on the
    // device at all. (Under the old one-tap option it also meant "none authorised yet", which is
    // why that option was wrong for this screen.)
    is NoCredentialException -> AuthFailure.NoAccountAvailable

    is GetCredentialException -> AuthFailure.Unexpected(this)

    else -> AuthFailure.Unexpected(this)
}
